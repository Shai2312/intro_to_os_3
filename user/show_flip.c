// ── Rendering helpers ─────────────────────────────────────────────────

static void
putpixel(uint32 *fb, int x, int y, uint32 color)
{
    fb[y * SCREEN_W + x] = color;
}

static void
fill_rect(uint32 *fb, int x, int y, int w, int h, uint32 color)
{
    if (x < 0)
    {
        w += x;
        x = 0;
    }
    if (y < 0)
    {
        h += y;
        y = 0;
    }
    if (x + w > SCREEN_W)
        w = SCREEN_W - x;
    if (y + h > SCREEN_H)
        h = SCREEN_H - y;
    if (w <= 0 || h <= 0)
        return;

    for (int dy = 0; dy < h; dy++)
        for (int dx = 0; dx < w; dx++)
            putpixel(fb, x + dx, y + dy, color);
}

static uint32
rgb(int r, int g, int b)
{
    return ((uint32)r << 16) | ((uint32)g << 8) | (uint32)b;
}

static void
draw_rainbow_a(uint32 *fb)
{
    const uint32 colors[6] = {
        rgb(255, 40, 40),
        rgb(255, 130, 20),
        rgb(255, 220, 40),
        rgb(80, 220, 100),
        rgb(40, 130, 255),
        rgb(170, 80, 220),
    };
    const int xs[6] = {40, 80, 120, 160, 200, 240};
    for (int row = 0; row < 6; row++)
    {
        int y = 120 + row * 18;
        for (int i = 0; i < 6; i++)
            fill_rect(fb, xs[i], y, 30, 12, colors[row]);
    }
}

